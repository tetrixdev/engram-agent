package snapshot

import (
	"context"
	"sort"
	"strings"
)

// Rule is one -A line of the filter table.
type Rule struct {
	Family  string  `json:"family"` // v4, v6
	Chain   string  `json:"chain"`
	Rule    string  `json:"rule"`    // the line after "-A <chain> ", without the comment match, whitespace collapsed
	Comment *string `json:"comment"` // the comment's text, unescaped; null when none
	Target  *string `json:"target"`  // the value after -j (or -g); null when none
}

// token is one argument of an iptables-save line, with where it sat.
type token struct {
	val        string // unquoted, unescaped
	start, end int    // its span in the line, quotes included
}

// tokenize splits an iptables-save line as iptables-save quotes it: an
// argument with spaces or quotes is written in double quotes, with `"` and
// `\` escaped by a backslash.
func tokenize(s string) []token {
	var out []token
	i := 0
	for i < len(s) {
		for i < len(s) && (s[i] == ' ' || s[i] == '\t') {
			i++
		}
		if i >= len(s) {
			break
		}
		start := i
		var b strings.Builder
		inQ := false
		for i < len(s) {
			c := s[i]
			if inQ {
				if c == '\\' && i+1 < len(s) {
					b.WriteByte(s[i+1])
					i += 2
					continue
				}
				if c == '"' {
					inQ = false
					i++
					continue
				}
				b.WriteByte(c)
				i++
				continue
			}
			if c == ' ' || c == '\t' {
				break
			}
			if c == '"' {
				inQ = true
				i++
				continue
			}
			b.WriteByte(c)
			i++
		}
		out = append(out, token{val: b.String(), start: start, end: i})
	}
	return out
}

// ParseSave reads the filter table of iptables-save (or ip6tables-save)
// output: the rules in their order, and the built-in chains' policies.
func ParseSave(out, family string) ([]Rule, map[string]string) {
	rules := []Rule{}
	policies := map[string]string{}
	table := ""
	for _, line := range strings.Split(out, "\n") {
		line = strings.TrimRight(line, "\r")
		switch {
		case strings.HasPrefix(line, "*"):
			table = strings.TrimSpace(line[1:])
			continue
		case table != "filter":
			continue
		case strings.HasPrefix(line, ":"):
			f := strings.Fields(line[1:])
			if len(f) >= 2 && f[1] != "-" {
				policies[f[0]] = f[1]
			}
			continue
		case !strings.HasPrefix(line, "-A "):
			continue
		}
		toks := tokenize(line)
		if len(toks) < 2 {
			continue
		}
		r := Rule{Family: family, Chain: toks[1].val}
		var keep []string
		rest := toks[2:]
		for i := 0; i < len(rest); i++ {
			t := rest[i]
			// -m comment --comment "<text>": recorded apart, left out of the rule.
			if t.val == "-m" && i+3 < len(rest) && rest[i+1].val == "comment" && rest[i+2].val == "--comment" {
				if r.Comment == nil {
					c := rest[i+3].val
					r.Comment = &c
				}
				i += 3
				continue
			}
			if (t.val == "-j" || t.val == "-g") && i+1 < len(rest) && r.Target == nil {
				tg := rest[i+1].val
				r.Target = &tg
			}
			keep = append(keep, line[t.start:t.end])
		}
		r.Rule = strings.Join(keep, " ")
		rules = append(rules, r)
	}
	return rules, policies
}

// Firewall reads the filter table of both families.
func (e Env) Firewall(ctx context.Context) Section {
	meta := map[string]any{}
	pol := map[string]any{}
	var all []Rule
	var errs []string
	backend := ""
	for _, fam := range []struct{ family, bin string }{{"v4", "iptables-save"}, {"v6", "ip6tables-save"}} {
		p := e.lookPath(fam.bin, "usr/sbin", "sbin")
		if p == "" {
			errs = append(errs, fam.bin+" not found in /usr/sbin or /sbin")
			continue
		}
		out, err := e.Run(ctx, p, "-t", "filter")
		if err != nil {
			errs = append(errs, fam.bin+": "+err.Error())
			continue
		}
		rules, policies := ParseSave(string(out), fam.family)
		all = append(all, rules...)
		pol[fam.family] = policies
		if backend == "" {
			backend = saveBackend(string(out))
		}
	}
	// Chains sorted by family and name; within a chain the rules keep
	// their order, which is the order the kernel checks them in.
	sort.SliceStable(all, func(i, j int) bool {
		if all[i].Family != all[j].Family {
			return all[i].Family < all[j].Family
		}
		return all[i].Chain < all[j].Chain
	})
	if all == nil {
		all = []Rule{}
	}
	meta["policies"] = pol
	if backend != "" {
		meta["backend"] = backend
	}
	return Section{Items: all, Meta: meta, Error: joinErrs(errs)}
}

// saveBackend reads iptables-save's header: "# Generated by iptables-save
// v1.8.10 (nf_tables) on ..." or "... (legacy) ..."; older legacy builds
// name no backend.
func saveBackend(out string) string {
	for _, l := range strings.Split(out, "\n") {
		if !strings.HasPrefix(l, "# Generated by") {
			continue
		}
		if strings.Contains(l, "nf_tables") {
			return "nf_tables"
		}
		return "legacy"
	}
	return ""
}
