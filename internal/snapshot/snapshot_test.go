func TestUsersAndKeys(t *testing.T) {
	root, fps := fixtureRoot(t)
	e := Env{Root: root}
	users, homes, err := e.Users()
	if err != nil {
		t.Fatalf("error %s", *err)
	}
	want := []User{
		{Login: "deploy", UID: 1000, Shell: "/bin/bash", Groups: []string{"adm", "deploy", "docker"}, Sudo: "nopasswd"},
		{Login: "jasper", UID: 1001, Shell: "/usr/bin/zsh", Groups: []string{"adm", "docker", "jasper", "sudo"}, Sudo: "password"},
		{Login: "ops", UID: 1002, Shell: "/bin/bash", Groups: []string{"ops"}, Sudo: "none"},
		{Login: "root", UID: 0, Shell: "/bin/bash", Groups: []string{"root"}, Sudo: "password"},
	}
	if !reflect.DeepEqual(users, want) {
		gb, _ := json.Marshal(users)
		t.Fatalf("users %s", gb)
	}
	if homes["jasper"] != "/home/jasper" {
		t.Errorf("homes %v", homes)
	}
	s := e.SSHKeys(users, homes)
	if s.Error != nil {
		t.Fatalf("keys error %s", *s.Error)
	}
	keys := s.Items.([]Key)
	if len(keys) != 3 || keys[0].Login != "deploy" || keys[0].Fingerprint != fps["deploy"] || keys[0].Comment == nil || *keys[0].Comment != "ci" {
		gb, _ := json.Marshal(keys)
		t.Fatalf("keys %s", gb)
	}
	got := map[string]Key{}
	for _, k := range keys[1:] {
		got[k.Fingerprint] = k
	}
	if k := got[fps["jasper1"]]; k.Login != "jasper" || k.Options || deref(k.Comment) != "jasper@laptop" {
		t.Errorf("jasper's first key %+v", k)
	}
	if k := got[fps["jasper2"]]; !k.Options || k.Comment != nil {
		t.Errorf("jasper's second key %+v", k)
	}
	// The key itself is never in the output.
	b, _ := json.Marshal(s)
	if strings.Contains(string(b), "AAAA") {
		t.Fatalf("a key blob in the output: %s", b)
	}

	// A FIFO in place of authorized_keys does not hang the snapshot.
	fifo := filepath.Join(root, "home/ops/.ssh/authorized_keys")
	os.MkdirAll(filepath.Dir(fifo), 0o755)
	if err := syscall.Mkfifo(fifo, 0o644); err != nil {
		t.Fatal(err)
	}
	done := make(chan Section, 1)
	go func() { done <- e.SSHKeys(users, homes) }()
	select {
	case s = <-done:
		if s.Error == nil || !strings.Contains(*s.Error, "not a regular file") {
			t.Errorf("fifo: %v", deref(s.Error))
		}
	case <-time.After(5 * time.Second):
		t.Fatal("a FIFO authorized_keys blocked the snapshot")
	}
}

