func write(t *testing.T, root, rel, content string, mode os.FileMode) {
	t.Helper()
	p := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), mode); err != nil {
		t.Fatal(err)
	}
}

func fixture(t *testing.T, name string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func sp(s string) *string { return &s }

func TestParseSave(t *testing.T) {
	rules, pol := ParseSave(fixture(t, "iptables-save.txt"), "v4")
	if !reflect.DeepEqual(pol, map[string]string{"INPUT": "DROP", "FORWARD": "DROP", "OUTPUT": "ACCEPT"}) {
		t.Fatalf("policies %v", pol)
	}
	byRule := map[string]Rule{}
	for _, r := range rules {
		if r.Family != "v4" {
			t.Fatalf("family %q", r.Family)
		}
		byRule[r.Chain+" "+r.Rule] = r
	}
	cases := []struct {
		key     string
		comment *string
		target  *string
	}{
		{"INPUT -j ts-input", nil, sp("ts-input")},
		{"INPUT -i lo -j ACCEPT", sp("loopback: the host talks to itself over lo"), sp("ACCEPT")},
		{"INPUT -p tcp -m tcp --dport 443 -j ACCEPT", sp("web: proxy serves the sites; 80 for ACME"), sp("ACCEPT")},
		// An escaped quote and backslash inside the comment are unescaped.
		{"INPUT -p tcp -m tcp --dport 8443 -j ACCEPT", sp(`admin: the "panel" on 8443, path C:\panel kept`), sp("ACCEPT")},
		// Whitespace collapsed.
		{"INPUT -p tcp -m tcp --dport 22 -j ACCEPT", nil, sp("ACCEPT")},
		{"INPUT -p tcp -m tcp --dport 9000 -j ACCEPT", sp("todo"), sp("ACCEPT")},
		// A quoted argument that is not a comment stays as written.
		{`INPUT -p tcp -m tcp --dport 9100 -j LOG --log-prefix "node exporter: "`, nil, sp("LOG")},
		{"FORWARD -j DOCKER-USER", nil, sp("DOCKER-USER")},
		{"FORWARD -j DOCKER-FORWARD", nil, sp("DOCKER-FORWARD")},
		{"DOCKER ! -i docker0 -o docker0 -j DROP", nil, sp("DROP")},
		// iptables-save escapes a single quote too.
		{"DOCKER-USER -s 172.17.0.0/16 -j RETURN", sp("docker-egress: containers reach the internet from Docker's first address pool"), sp("RETURN")},
		{"DOCKER-USER -j DROP", sp("docker: drop what the host rules above did not let through"), sp("DROP")},
		{"ts-forward -i tailscale0 -j MARK --set-xmark 0x40000/0xff0000", nil, sp("MARK")},
		{"ts-input -i lo -s 100.101.1.2/32 -j ACCEPT", nil, sp("ACCEPT")},
	}
	for _, c := range cases {
		r, ok := byRule[c.key]
		if !ok {
			t.Errorf("no rule %q among %d", c.key, len(rules))
			continue
		}
		if !reflect.DeepEqual(r.Comment, c.comment) || !reflect.DeepEqual(r.Target, c.target) {
			t.Errorf("%q: comment %v target %v", c.key, deref(r.Comment), deref(r.Target))
		}
	}
	if len(rules) != 18 {
		t.Errorf("%d rules, want 18 (the nat table is not read)", len(rules))
	}
	// Rules keep their order within a chain.
	if rules[0].Rule != "-j ts-input" || rules[1].Rule != "-i lo -j ACCEPT" {
		t.Errorf("order: %q, %q", rules[0].Rule, rules[1].Rule)
	}
	if b := saveBackend(fixture(t, "iptables-save.txt")); b != "nf_tables" {
		t.Errorf("backend %q", b)
	}
	if b := saveBackend("# Generated by iptables-save v1.8.7 on Mon\n*filter\n"); b != "legacy" {
		t.Errorf("legacy backend %q", b)
	}
}

func deref(s *string) string {
	if s == nil {
		return "<nil>"
	}
	return *s
}

func TestTokenize(t *testing.T) {
	cases := map[string][]string{
		`-A INPUT -j ACCEPT`:                      {"-A", "INPUT", "-j", "ACCEPT"},
		`-m comment --comment "a b"`:              {"-m", "comment", "--comment", "a b"},
		`--comment "say \"hi\" \\ there"  -j X`:   {"--comment", `say "hi" \ there`, "-j", "X"},
		`--comment ""`:                            {"--comment", ""},
		"  -A\tFORWARD   -j   DOCKER-USER   ":     {"-A", "FORWARD", "-j", "DOCKER-USER"},
		`--log-prefix "x: " -m comment --comment`: {"--log-prefix", "x: ", "-m", "comment", "--comment"},
	}
	for in, want := range cases {
		var got []string
		for _, tk := range tokenize(in) {
			got = append(got, tk.val)
		}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("tokenize(%q) = %q, want %q", in, got, want)
		}
	}
}

// fakeRun answers like the host's programs would, from fixtures.
func fakeRun(t *testing.T, root string, answers map[string]func() ([]byte, error)) func(context.Context, string, ...string) ([]byte, error) {
	return func(_ context.Context, path string, args ...string) ([]byte, error) {
		rel := strings.TrimPrefix(path, root)
		if f, ok := answers[rel]; ok {
			return f()
		}
		t.Errorf("unexpected command %s %v", rel, args)
		return nil, errors.New("no such command")
	}
}

func TestFirewallSection(t *testing.T) {
	root := t.TempDir()
	write(t, root, "usr/sbin/iptables-save", "#!/bin/sh\n", 0o755)
	write(t, root, "sbin/ip6tables-save", "#!/bin/sh\n", 0o755)
	var gotArgs []string
	e := Env{Root: root}
	e.Run = func(_ context.Context, path string, args ...string) ([]byte, error) {
		gotArgs = args
		switch strings.TrimPrefix(path, root) {
		case "/usr/sbin/iptables-save":
			return []byte(fixture(t, "iptables-save.txt")), nil
		case "/sbin/ip6tables-save":
			return []byte(fixture(t, "ip6tables-save.txt")), nil
		}
		return nil, errors.New("unexpected " + path)
	}
	s := e.Firewall(context.Background())
	if s.Error != nil {
		t.Fatalf("error %s", *s.Error)
	}
	if !reflect.DeepEqual(gotArgs, []string{"-t", "filter"}) {
		t.Errorf("args %v", gotArgs)
	}
	rules := s.Items.([]Rule)
	if len(rules) != 20 || rules[0].Family != "v4" || rules[len(rules)-1].Family != "v6" {
		t.Fatalf("%d rules", len(rules))
	}
	// Sorted by family and chain; DOCKER before FORWARD before INPUT before ts-*.
	var chains []string
	for _, r := range rules {
		if r.Family == "v4" && (len(chains) == 0 || chains[len(chains)-1] != r.Chain) {
			chains = append(chains, r.Chain)
		}
	}
	if !reflect.DeepEqual(chains, []string{"DOCKER", "DOCKER-FORWARD", "DOCKER-USER", "FORWARD", "INPUT", "ts-forward", "ts-input"}) {
		t.Errorf("chain order %v", chains)
	}
	pol := s.Meta["policies"].(map[string]any)
	if pol["v6"].(map[string]string)["INPUT"] != "DROP" || s.Meta["backend"] != "nf_tables" {
		t.Errorf("meta %v", s.Meta)
	}

	// ip6tables-save missing: v4 still read, the error says what is missing.
	os.Remove(filepath.Join(root, "sbin/ip6tables-save"))
	s = e.Firewall(context.Background())
	if s.Error == nil || !strings.Contains(*s.Error, "ip6tables-save not found") || len(s.Items.([]Rule)) != 18 {
		t.Errorf("without ip6tables-save: %v %d", deref(s.Error), len(s.Items.([]Rule)))
	}
}

// dockerSocket serves a fake Docker Engine API on a unix socket.
func dockerSocket(t *testing.T, h http.HandlerFunc) string {
	t.Helper()
	dir, err := os.MkdirTemp("", "dock")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.RemoveAll(dir) })
	sock := filepath.Join(dir, "docker.sock")
	l, err := net.Listen("unix", sock)
	if err != nil {
		t.Fatal(err)
	}
	srv := httptest.NewUnstartedServer(h)
	srv.Listener = l
	srv.Start()
	t.Cleanup(srv.Close)
	return sock
}

