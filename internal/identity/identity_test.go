var update = flag.Bool("update", false, "rewrite testdata/signature-vector.json")

// Vector is the fixed signature test vector, shared with Engram's Node side
// (agent/testdata/signature-vector.json): the same seed, agent id, time and
// body must give the same public key, fingerprint, signed string and signature.
type Vector struct {
	Note         string `json:"note"`
	SeedHex      string `json:"private_key_seed_hex"`
	PublicKeyB64 string `json:"public_key_b64"`
	Fingerprint  string `json:"fingerprint"`
	AgentID      string `json:"agent_id"`
	Time         int64  `json:"time"`
	Body         string `json:"body"`
	BodySHA256   string `json:"body_sha256_hex"`
	SignedString string `json:"signed_string"`
	Signature    string `json:"signature_b64"`
}

func makeVector() Vector {
	seed := make([]byte, 32)
	for i := range seed {
		seed[i] = byte(i)
	}
	key := ed25519.NewKeyFromSeed(seed)
	pub := key.Public().(ed25519.PublicKey)
	v := Vector{
		Note:    "engram-agent wire protocol v1. Headers: X-Engram-Agent: agent_id, X-Engram-Time: time, X-Engram-Signature: signature_b64. The signature is ed25519 over the UTF-8 bytes of signed_string. Generated by agent/internal/identity (go test -run Vector -update).",
		SeedHex: hex.EncodeToString(seed),
		AgentID: "3f2b8c1e-5a4d-4e6f-9b7a-1c2d3e4f5a6b",
		Time:    1792400000,
		Body:    `{"agent_version":"0.1.0","events":[{"type":"alert.raised","ref":"memory_pct","occurred_at":"2026-10-19T12:00:00Z","key":"0f1e2d3c4b5a69788796a5b4c3d2e1f0","state":{"rule":"memory_pct","level":"warn"}}]}`,
	}
	v.PublicKeyB64 = base64.StdEncoding.EncodeToString(pub)
	v.Fingerprint = Fingerprint(pub)
	sum := SignedString(v.AgentID, v.Time, []byte(v.Body))
	v.SignedString = string(sum)
	h := ed25519.Sign(key, sum)
	v.Signature = base64.StdEncoding.EncodeToString(h)
	b := []byte(v.Body)
	v.BodySHA256 = hex.EncodeToString(sha(b))
	return v
}

func TestSignatureVector(t *testing.T) {
	v := makeVector()
	path := filepath.Join("..", "..", "testdata", "signature-vector.json")
	if *update {
		b, _ := json.MarshalIndent(v, "", "  ")
		if err := os.WriteFile(path, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (go test ./internal/identity -run Vector -update writes it)", err)
	}
	var want Vector
	if err := json.Unmarshal(b, &want); err != nil {
		t.Fatal(err)
	}
	if want != v {
		t.Fatalf("the vector changed:\nfile %+v\nnow  %+v", want, v)
	}
	// Sign agrees with the vector, and the signature verifies.
	seed, _ := hex.DecodeString(v.SeedHex)
	key := ed25519.NewKeyFromSeed(seed)
	if got := Sign(key, v.AgentID, v.Time, []byte(v.Body)); got != v.Signature {
		t.Fatalf("Sign = %s", got)
	}
	pub, _ := base64.StdEncoding.DecodeString(v.PublicKeyB64)
	sig, _ := base64.StdEncoding.DecodeString(v.Signature)
	if !ed25519.Verify(pub, []byte(v.SignedString), sig) {
		t.Fatal("the vector's signature does not verify")
	}
	if !regexp.MustCompile(`^[A-Z2-7]{4}-[A-Z2-7]{4}-[A-Z2-7]{4}-[A-Z2-7]{4}$`).MatchString(v.Fingerprint) {
		t.Fatalf("fingerprint shape %q", v.Fingerprint)
	}
}

func TestKeyAndIdentityFiles(t *testing.T) {
	dir := t.TempDir()
	if _, err := Load(dir); !os.IsNotExist(err) {
		t.Fatalf("not enrolled: %v", err)
	}
	k1, err := LoadOrCreateKey(dir)
	if err != nil {
		t.Fatal(err)
	}
	fi, _ := os.Stat(filepath.Join(dir, KeyFile))
	if fi.Mode().Perm() != 0o600 {
		t.Fatalf("key mode %v", fi.Mode())
	}
	k2, err := LoadOrCreateKey(dir)
	if err != nil || !k1.Equal(k2) {
		t.Fatal("the key changed on a second load")
	}
	id := &Identity{URL: "https://e.example.org", AgentID: "a1", Fingerprint: Fingerprint(k1.Public().(ed25519.PublicKey))}
	if err := Save(dir, id); err != nil {
		t.Fatal(err)
	}
	got, err := Load(dir)
	if err != nil || got.AgentID != "a1" || got.URL != id.URL {
		t.Fatalf("%+v %v", got, err)
	}
}

func TestNormalizeURL(t *testing.T) {
	ok := map[string]string{"https://e.example.org/": "https://e.example.org", "http://127.0.0.1:8080": "http://127.0.0.1:8080"}
	for in, want := range ok {
		if got, err := NormalizeURL(in); err != nil || got != want {
			t.Errorf("%s: %s %v", in, got, err)
		}
	}
	for _, bad := range []string{"http://e.example.org", "e.example.org", "https://e.example.org/?x=1"} {
		if _, err := NormalizeURL(bad); err == nil {
			t.Errorf("%s accepted", bad)
		}
	}
}

func sha(b []byte) []byte {
	s := sha256.Sum256(b)
	return s[:]
}
